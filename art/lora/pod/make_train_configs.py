#!/usr/bin/env python3
"""Write one ai-toolkit job config per persona into configs/<pack>-<tag>.yaml.

    python3 make_train_configs.py                      # every persona with a dataset folder present
    python3 make_train_configs.py --pack blogery --steps 2000

Datasets are expected at <dataset-root>/<pack>/<tag>/ (photos plus caption .txt files, see caption.py). A persona
without a folder is skipped with a note, so the script is safe to run before every photo set is in. The job name is
`<pack>-<tag>`, which is also the LoRA filename render.py loads, so the two never drift apart.
"""

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).parent
PERSONAS = HERE.parent / "personas.json"
CONFIGS = HERE / "configs"

TEMPLATE = """\
# Generated by make_train_configs.py for {name}; edit the generator, not this file.
job: extension
config:
  name: "{job}"
  process:
    - type: "sd_trainer"
      training_folder: "/workspace/output"
      device: cuda:0
      trigger_word: "{trigger}"
      network:
        type: "lora"
        linear: 16
        linear_alpha: 16
      save:
        dtype: float16
        save_every: 300
        max_step_saves_to_keep: 3
        push_to_hub: false
      datasets:
        - folder_path: "{folder}"
          caption_ext: "txt"
          caption_dropout_rate: 0.05
          shuffle_tokens: false
          cache_latents_to_disk: true
          resolution: [512, 768, 1024]
      train:
        batch_size: 1
        steps: {steps}
        gradient_accumulation_steps: 1
        train_unet: true
        train_text_encoder: false
        gradient_checkpointing: true
        noise_scheduler: "flowmatch"
        optimizer: "adamw8bit"
        lr: 1e-4
        ema_config:
          use_ema: true
          ema_decay: 0.99
        dtype: bf16
      model:
        name_or_path: "black-forest-labs/FLUX.1-dev"
        is_flux: true
        quantize: true
        low_vram: true
      sample:
        sampler: "flowmatch"
        sample_every: 300
        width: 480
        height: 672
        prompts:
          - "[trigger], a caricature of [trigger], flat vector caricature, bold outlines, poster colours, head and shoulders, plain background"
          - "[trigger], portrait photo of [trigger], neutral background"
        neg: ""
        seed: 42
        walk_seed: true
        guidance_scale: 3.5
        sample_steps: 20
meta:
  name: "{job}"
  version: "1.0"
"""


def render_config(persona: dict, *, dataset_root: str, steps: int) -> str:
    job = f"{persona['pack']}-{persona['tag']}"
    return TEMPLATE.format(
        name=persona["name"],
        job=job,
        trigger=persona["trigger"],
        folder=f"{dataset_root}/{persona['pack']}/{persona['tag']}",
        steps=steps,
    )


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dataset-root", default="/workspace/dataset")
    parser.add_argument("--steps", type=int, default=1800, help="1500-2500 for about 20 photos")
    parser.add_argument("--pack")
    parser.add_argument("--force", action="store_true", help="write configs even without a dataset folder")
    args = parser.parse_args(argv)

    personas = json.loads(PERSONAS.read_text())
    if args.pack:
        personas = [p for p in personas if p["pack"] == args.pack]
    CONFIGS.mkdir(exist_ok=True)
    written = 0
    for persona in personas:
        folder = Path(args.dataset_root) / persona["pack"] / persona["tag"]
        photos = [p for p in folder.glob("*") if p.suffix.lower() in {".jpg", ".jpeg", ".png", ".webp"}] if folder.is_dir() else []
        if not photos and not args.force:
            print(f"skip {persona['name']}: no photos in {folder}")
            continue
        if photos and len(photos) < 12:
            print(f"warn {persona['name']}: only {len(photos)} photos, likeness will be weak (aim for 15-25)")
        target = CONFIGS / f"{persona['pack']}-{persona['tag']}.yaml"
        target.write_text(render_config(persona, dataset_root=args.dataset_root, steps=args.steps))
        written += 1
    print(f"{written} configs in {CONFIGS}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
